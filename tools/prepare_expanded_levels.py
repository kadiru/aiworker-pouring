"""Freeze independently supervised RGB/color fits after complete tracker admission."""
import json
from pathlib import Path
from fit_dynamic_rim import ROOT,read,sha,protected_unchanged

def main():
    assert not (ROOT/'component-selection.json').exists()
    assert not list(Path('/workspace/outputs/fountain').glob('*/*SD_A_motion_holdout_*/parameters.json'))
    protected_unchanged();c=read(ROOT/'level-cache-v4.json')
    assert c['passed'] and read(ROOT/'tracker-t2.json')['passed']
    assert c['cache_sha256']==sha(ROOT/'level-cache-v4.npz') and c['metadata_sha256']==sha(ROOT/'level-cache-v4-meta.json')
    assert c['tracker_sha256']==sha(ROOT/'tracker-t2.pt') and c['tracker_module_sha256']==sha(ROOT/'dynamic_cup_tracker.py')
    files=['protocol.json','plan.json','candidate.json','tracker-t2.pt','tracker-t2.json','tracker-t2-protocol.json',
           'dynamic_cup_tracker.py','level-cache-v4.npz','level-cache-v4-meta.json','level-cache-v4.json',
           'fit_expanded_levels.py','prepare_expanded_levels.py','repair_level_model.py','repair_level_model_v2.py',
           'fit_dynamic_pair.py','scale_level_cnn.py','scale_rim_augmentation.py','scale_color_mask.py',
           'pair-r5-rgb.pt','pair-r5-color.pt','perception_repair_data.py','cache_expanded_levels.py']
    cfg=dict(round='r8',seed=261110608,locator='tracker-t2.pt',protocol_sha256=sha(ROOT/'protocol.json'),
             frozen_files={n:sha(ROOT/n) for n in files},epochs=800,batch_size=64,lr=.00015,
             lr_steps=[401,601],jitter_pixels=1.5,top_quartile_weight=.25,wall_seconds=1800,max_episode_mae=.02,
             initialization=dict(rgb='pair-r5-rgb.pt',color='pair-r5-color.pt'),
             method='Two independent supervised 179409-parameter RGB/color-outline CNNs. AdamW; MSE plus 0.25 worst-quartile MSE; balanced motion, size and episode sampling. No RL or cross-model loss.',
             scope='207 training / 36 validation episodes with all crops regenerated by tracker-t2. Original gates and added every-episode MAE <2 percentage points retained. No reserved images or runtime activation.')
    with (ROOT/'pair-r8-protocol.json').open('x') as f:json.dump(cfg,f,indent=2);f.write('\n')
    print(json.dumps(dict(prepared='r8',counts=c['counts'])),flush=True)

if __name__=='__main__':main()
